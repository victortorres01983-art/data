CREATE TABLE TIPOS_ATENCION (
    ID_TIPO_ATENCION NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DESCRIPCION VARCHAR2(100) NOT NULL UNIQUE,
    PREFIJO VARCHAR2(3) NOT NULL UNIQUE,
    ACTIVO CHAR(1) DEFAULT 'S' NOT NULL CHECK (ACTIVO IN ('S','N'))
);

CREATE TABLE ESTADOS_TICKET (
    ID_ESTADO NUMBER PRIMARY KEY,
    DESCRIPCION VARCHAR2(30) NOT NULL UNIQUE
);

CREATE TABLE TICKETS (
    ID_TICKET NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ID_TIPO_ATENCION NUMBER NOT NULL REFERENCES TIPOS_ATENCION(ID_TIPO_ATENCION),
    ID_ESTADO NUMBER DEFAULT 1 NOT NULL REFERENCES ESTADOS_TICKET(ID_ESTADO),
    NUMERO_TICKET VARCHAR2(15) NOT NULL,
    FECHA_EMISION DATE DEFAULT SYSDATE NOT NULL,
    FECHA_LLAMADO DATE
);

CREATE UNIQUE INDEX UQ_TICKET_DIARIO ON TICKETS (TRUNC(FECHA_EMISION), NUMERO_TICKET);
CREATE INDEX IDX_TICKET_ESTADO ON TICKETS (ID_ESTADO, FECHA_EMISION);
CREATE INDEX IDX_TICKET_TIPO ON TICKETS (ID_TIPO_ATENCION);

